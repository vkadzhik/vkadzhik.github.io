// Arena tokens: Figma variables export → DTCG JSON + CSS custom properties.
// Usage: node tokens/build.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync(new URL("./figma-export.json", import.meta.url)));
const byName = Object.fromEntries(src.out.map(c => [c.collection, c]));
const prim = Object.fromEntries(byName.Primitives.vars.map(v => [v.n, v.v.Value]));

const cssVar = n => "--" + n.replace(/\//g, "-").replace(/\s+/g, "-").toLowerCase();
const ref = v => (typeof v === "string" && v.startsWith("{")) ? v.slice(1, -1) : null;
const resolve = v => (ref(v) ? prim[ref(v)] : v);

// ---------- DTCG JSON (design-tokens.json) ----------
const dtcg = { primitive: {}, theme: { light: {}, dark: {} }, size: {}, typography: {} };
const put = (obj, path, val) => { const p = path.split("/"); let o = obj; p.slice(0, -1).forEach(k => (o = o[k] ??= {})); o[p.at(-1)] = val; };
for (const v of byName.Primitives.vars) put(dtcg.primitive, v.n, { $type: "color", $value: v.v.Value });
for (const v of byName.Theme.vars) {
  put(dtcg.theme.light, v.n, { $type: "color", $value: v.v.Light });
  put(dtcg.theme.dark, v.n, { $type: "color", $value: v.v.Dark });
}
for (const v of byName.Size.vars) put(dtcg.size, v.n, { $type: "dimension", $value: v.v.Default + "px" });
const weight = { Regular: 400, Medium: 500, SemiBold: 600, Bold: 700 };
for (const s of src.styles) {
  const [family, style] = [s.f.split(" ").slice(0, -1).join(" "), s.f.split(" ").at(-1)];
  put(dtcg.typography, s.n.toLowerCase().replace(/\s+/g, "-"), { $type: "typography", $value: {
    fontFamily: family, fontWeight: weight[style] ?? 400, fontSize: s.s + "px", lineHeight: s.lh + "px", letterSpacing: (s.ls / 100) + "em" } });
}
writeFileSync(new URL("./design-tokens.json", import.meta.url), JSON.stringify(dtcg, null, 2));

// ---------- CSS ----------
const L = [];
L.push("/* Generated by tokens/build.mjs from Figma variables (Arena). Do not edit by hand. */");
L.push(":root {");
L.push("  /* primitives */");
for (const v of byName.Primitives.vars) L.push(`  ${cssVar(v.n)}: ${v.v.Value};`);
L.push("  /* size */");
for (const v of byName.Size.vars) L.push(`  ${cssVar(v.n)}: ${v.v.Default}px;`);
L.push("  /* typography */");
L.push(`  --font-family: "Onest", system-ui, -apple-system, "Segoe UI", sans-serif;`);
for (const s of src.styles) {
  const n = cssVar("type/" + s.n);
  const style = s.f.split(" ").at(-1);
  L.push(`  ${n}: ${weight[style] ?? 400} ${s.s}px/${s.lh}px var(--font-family);`);
  L.push(`  ${n}-tracking: ${s.ls / 100}em;`);
}
L.push("}");
const themeBlock = (sel, mode) => {
  L.push(`${sel} {`);
  L.push(`  color-scheme: ${mode === "Light" ? "light" : "dark"};`);
  for (const v of byName.Theme.vars) {
    const r = ref(v.v[mode]);
    L.push(`  ${cssVar(v.n)}: ${r ? `var(${cssVar(r)})` : v.v[mode]};`);
  }
  L.push("}");
};
themeBlock(":root, [data-theme=\"light\"]", "Light");
themeBlock("[data-theme=\"dark\"]", "Dark");
L.push("@media (prefers-color-scheme: dark) {");
L.push("  :root:not([data-theme=\"light\"]) {");
L.push("    color-scheme: dark;");
for (const v of byName.Theme.vars) { const r = ref(v.v.Dark); L.push(`    ${cssVar(v.n)}: ${r ? `var(${cssVar(r)})` : v.v.Dark};`); }
L.push("  }");
L.push("}");
writeFileSync(new URL("../css/tokens.css", import.meta.url), L.join("\n") + "\n");

// ---------- JS manifest for the docs page ----------
const manifest = {
  primitives: byName.Primitives.vars.map(v => ({ name: v.n, css: cssVar(v.n), value: v.v.Value })),
  theme: byName.Theme.vars.map(v => ({ name: v.n, css: cssVar(v.n), light: v.v.Light, dark: v.v.Dark, lightHex: resolve(v.v.Light), darkHex: resolve(v.v.Dark) })),
  size: byName.Size.vars.map(v => ({ name: v.n, css: cssVar(v.n), value: v.v.Default })),
  type: src.styles.map(s => ({ name: s.n, css: cssVar("type/" + s.n), font: s.f, size: s.s, lh: s.lh, ls: s.ls })),
};
writeFileSync(new URL("../js/tokens.js", import.meta.url), "export const TOKENS = " + JSON.stringify(manifest) + ";\n");
console.log(`tokens: ${manifest.primitives.length} primitives, ${manifest.theme.length} theme, ${manifest.size.length} size, ${manifest.type.length} type styles`);
